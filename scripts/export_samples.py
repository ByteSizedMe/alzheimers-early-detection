"""Export a labelled set of sample scans for dragging into the dashboard.

    python scripts/export_samples.py

Writes to ``<Desktop>/Alzheimers-Sample-Scans`` by default. Files are drawn
from the held-out **test** split, so nothing here was seen during training and
the model's answers are a fair check rather than a recital.

Each filename states its true stage, which makes the folder self-checking: the
interface's prediction either matches the name or it does not. A couple of
known-misclassified slices are included on purpose — a demo where everything is
correct teaches a reviewer nothing about the failure modes.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
CLASSES = ("NC", "EMCI", "LMCI", "AD")

STAGE_NAMES = {
    "NC": "normal-cognition",
    "EMCI": "early-MCI",
    "LMCI": "late-MCI",
    "AD": "alzheimers",
}

README = """Alzheimer's Early Detection — Sample Scans
================================================

Open http://localhost:8000 and drag any of these PNGs in -- or just click
the matching thumbnail, since the interface lists this folder automatically.

Each filename states the scan's TRUE stage, so you can check the model's
answer against it:

    NC_normal-cognition_01.png     -> should predict NC
    EMCI_early-MCI_01.png          -> should predict EMCI
    LMCI_late-MCI_01.png           -> should predict LMCI
    AD_alzheimers_01.png           -> should predict AD

The four stages, in order of severity:

    NC     Normal cognition
    EMCI   Early mild cognitive impairment
    LMCI   Late mild cognitive impairment
    AD     Alzheimer's disease

Files beginning with "MISREAD_" are cases the model gets WRONG. They are
included deliberately: the filename records both the true stage and what the
model predicted. Load one and look at the Grad-CAM map to see what it keyed on.

{split_note}

IMPORTANT
---------
These are SYNTHETIC phantom images, not real brain scans. They were generated
to exercise the pipeline while real ADNI data access is pending. They encode
stage as a geometric difference in ventricle size, cortical thickness, and
hippocampal area — enough to prove the system works end to end, but they carry
no clinical meaning whatsoever.

Generated by scripts/export_samples.py in the alzheimers-detection project.
"""


def default_output_dir() -> Path:
    """Desktop, preferring the OneDrive-redirected one when it exists."""
    for candidate in (
        Path.home() / "OneDrive" / "Desktop",
        Path.home() / "Desktop",
    ):
        if candidate.is_dir():
            return candidate / "Alzheimers-Sample-Scans"
    return REPO_ROOT / "data" / "samples"


def load_predictions() -> dict[str, str]:
    """Map source path -> predicted stage, for slices already explained."""
    report = REPO_ROOT / "artifacts" / "evaluation_test.json"
    if not report.exists():
        return {}

    payload = json.loads(report.read_text(encoding="utf-8"))
    return {
        record["source"]: record["predicted"]
        for record in payload.get("gradcam", [])
        if "source" in record
    }


def export(out_dir: Path, per_class: int, include_errors: bool) -> tuple[int, int]:
    manifest_path = REPO_ROOT / "data" / "processed" / "test_manifest.csv"
    split_note = (
        "All scans are from the held-out test split — the model never saw them\n"
        "during training."
    )

    if manifest_path.exists():
        manifest = pd.read_csv(manifest_path)
    else:
        # Fall back to the raw pool so the script still works before Phase 1.
        from alzheimers.data.datasets import scan_image_directory

        manifest = scan_image_directory(REPO_ROOT / "data" / "raw", CLASSES)
        split_note = (
            "NOTE: taken from the raw image pool, because no test split exists yet.\n"
            "Some of these may have been used in training. Run\n"
            "`python -m alzheimers.data.prepare` for a clean held-out set."
        )

    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("*.png"):
        stale.unlink()

    predictions = load_predictions()

    # Scans the model misreads are exported under the MISREAD_ name only.
    # Without this they can also be picked for the plain labelled set, and the
    # folder ends up holding the same image twice under two different names --
    # which reads as two independent cases when it is one.
    misread_sources = {
        source
        for source, predicted in predictions.items()
        if include_errors and predicted != Path(source).parent.name
    }

    n_correct = 0
    for label in CLASSES:
        rows = manifest[manifest["label"] == label]
        rows = rows[~rows["path"].isin(misread_sources)]
        # Deterministic pick, so re-running does not reshuffle the folder.
        for i, (_, row) in enumerate(rows.head(per_class).iterrows(), start=1):
            source = Path(row["path"])
            if not source.exists():
                continue
            destination = out_dir / f"{label}_{STAGE_NAMES[label]}_{i:02d}.png"
            shutil.copy2(source, destination)
            n_correct += 1

    n_errors = 0
    if include_errors:
        for source_path, predicted in predictions.items():
            source = Path(source_path)
            true_label = source.parent.name
            if predicted == true_label or not source.exists():
                continue
            destination = out_dir / f"MISREAD_true-{true_label}_predicted-{predicted}.png"
            shutil.copy2(source, destination)
            n_errors += 1

    (out_dir / "README.txt").write_text(
        README.format(split_note=split_note), encoding="utf-8"
    )
    return n_correct, n_errors


def main() -> None:
    parser = argparse.ArgumentParser(description="Export sample scans to the Desktop")
    parser.add_argument("--out", default=None, help="output folder (default: Desktop)")
    parser.add_argument("--per-class", type=int, default=3, help="scans per stage")
    parser.add_argument(
        "--no-errors", action="store_true", help="omit known-misclassified examples"
    )
    args = parser.parse_args()

    out_dir = Path(args.out) if args.out else default_output_dir()
    if not out_dir.is_absolute():
        out_dir = REPO_ROOT / out_dir

    n_correct, n_errors = export(out_dir, args.per_class, not args.no_errors)

    print(f"[samples] {n_correct} labelled scans -> {out_dir}")
    if n_errors:
        print(f"[samples] {n_errors} known-misclassified scans included (MISREAD_*)")
    print(f"[samples] wrote {out_dir / 'README.txt'}")
    print("\nOpen http://localhost:8000 -- these appear as clickable thumbnails.")


if __name__ == "__main__":
    main()
